-- FinanceAI multi-user Supabase/PostgreSQL schema.
-- The application can also initialize this schema automatically at startup.
-- Run this in the Supabase SQL Editor for an explicit migration.

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  name text not null,
  balance double precision not null default 0,
  type text not null default 'checking'
    check (type in ('checking','savings','credit','cash','investment')),
  unique (id, user_id)
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  type text not null check (type in ('income','expense')),
  amount double precision not null check (amount > 0),
  description text not null,
  category text not null,
  date text not null,
  created timestamptz default now(),
  account_id bigint,
  constraint transactions_account_user_fk
    foreign key (account_id, user_id)
    references public.accounts(id, user_id)
);

create table if not exists public.budgets (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  category text not null,
  limit_amt double precision not null check (limit_amt > 0),
  unique (user_id, category)
);

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid(),
  name text not null,
  target_amount double precision not null check (target_amount > 0),
  current_amount double precision not null default 0 check (current_amount >= 0),
  target_date text,
  category text not null default 'Savings',
  created timestamptz default now()
);

create index if not exists accounts_user_id_idx on public.accounts(user_id);
create index if not exists transactions_user_id_idx on public.transactions(user_id);
create index if not exists transactions_user_date_idx on public.transactions(user_id, date);
create index if not exists budgets_user_id_idx on public.budgets(user_id);
create index if not exists goals_user_id_idx on public.goals(user_id);

alter table public.accounts enable row level security;
alter table public.transactions enable row level security;
alter table public.budgets enable row level security;
alter table public.goals enable row level security;

grant select, insert, update, delete on public.accounts, public.transactions, public.budgets, public.goals to authenticated;
grant usage, select on all sequences in schema public to authenticated;

