-- FinanceAI V2: recurring schedules and user-scoped payment history links.
ALTER TABLE public.transactions
    ADD COLUMN IF NOT EXISTS recurring_item_id BIGINT;

CREATE TABLE IF NOT EXISTS public.recurring_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL DEFAULT auth.uid(),
    name TEXT NOT NULL,
    amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
    type TEXT NOT NULL CHECK (type IN ('income', 'expense')),
    category TEXT NOT NULL,
    frequency TEXT NOT NULL CHECK (frequency IN ('weekly', 'monthly', 'yearly')),
    next_due_date TEXT NOT NULL,
    schedule_day INTEGER NOT NULL CHECK (schedule_day BETWEEN 1 AND 31),
    schedule_month INTEGER CHECK (schedule_month BETWEEN 1 AND 12),
    account_id BIGINT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    last_recorded_due_date TEXT,
    created TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT recurring_item_account_user_fk
        FOREIGN KEY (account_id, user_id)
        REFERENCES public.accounts(id, user_id),
    UNIQUE (id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_recurring_items_user_due
    ON public.recurring_items(user_id, is_active, next_due_date);

CREATE UNIQUE INDEX IF NOT EXISTS idx_transactions_recurring_occurrence
    ON public.transactions(user_id, recurring_item_id, date)
    WHERE recurring_item_id IS NOT NULL;

ALTER TABLE public.recurring_items ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.recurring_items TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.recurring_items_id_seq TO authenticated;

DROP POLICY IF EXISTS recurring_items_select_own ON public.recurring_items;
DROP POLICY IF EXISTS recurring_items_insert_own ON public.recurring_items;
DROP POLICY IF EXISTS recurring_items_update_own ON public.recurring_items;
DROP POLICY IF EXISTS recurring_items_delete_own ON public.recurring_items;

CREATE POLICY recurring_items_select_own ON public.recurring_items
    FOR SELECT TO authenticated
    USING ((select auth.uid()) = user_id);
CREATE POLICY recurring_items_insert_own ON public.recurring_items
    FOR INSERT TO authenticated
    WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY recurring_items_update_own ON public.recurring_items
    FOR UPDATE TO authenticated
    USING ((select auth.uid()) = user_id)
    WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY recurring_items_delete_own ON public.recurring_items
    FOR DELETE TO authenticated
    USING ((select auth.uid()) = user_id);
