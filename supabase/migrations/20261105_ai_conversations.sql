-- FinanceAI V3: persistent, per-user AI conversations and messages.
CREATE TABLE IF NOT EXISTS public.ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL DEFAULT auth.uid(),
    title TEXT NOT NULL DEFAULT 'New chat',
    summary TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (id, user_id)
);

CREATE TABLE IF NOT EXISTS public.ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id UUID NOT NULL DEFAULT auth.uid(),
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ai_message_conversation_user_fk
        FOREIGN KEY (conversation_id, user_id)
        REFERENCES public.ai_conversations(id, user_id)
        ON DELETE CASCADE
);

ALTER TABLE public.ai_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_messages ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.ai_conversations, public.ai_messages TO authenticated;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;

DROP POLICY IF EXISTS ai_conversations_select_own ON public.ai_conversations;
DROP POLICY IF EXISTS ai_conversations_insert_own ON public.ai_conversations;
DROP POLICY IF EXISTS ai_conversations_update_own ON public.ai_conversations;
DROP POLICY IF EXISTS ai_conversations_delete_own ON public.ai_conversations;

CREATE POLICY ai_conversations_select_own ON public.ai_conversations
    FOR SELECT TO authenticated USING ((select auth.uid()) = user_id);
CREATE POLICY ai_conversations_insert_own ON public.ai_conversations
    FOR INSERT TO authenticated WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY ai_conversations_update_own ON public.ai_conversations
    FOR UPDATE TO authenticated
    USING ((select auth.uid()) = user_id)
    WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY ai_conversations_delete_own ON public.ai_conversations
    FOR DELETE TO authenticated USING ((select auth.uid()) = user_id);

DROP POLICY IF EXISTS ai_messages_select_own ON public.ai_messages;
DROP POLICY IF EXISTS ai_messages_insert_own ON public.ai_messages;
DROP POLICY IF EXISTS ai_messages_update_own ON public.ai_messages;
DROP POLICY IF EXISTS ai_messages_delete_own ON public.ai_messages;

CREATE POLICY ai_messages_select_own ON public.ai_messages
    FOR SELECT TO authenticated USING ((select auth.uid()) = user_id);
CREATE POLICY ai_messages_insert_own ON public.ai_messages
    FOR INSERT TO authenticated WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY ai_messages_update_own ON public.ai_messages
    FOR UPDATE TO authenticated
    USING ((select auth.uid()) = user_id)
    WITH CHECK ((select auth.uid()) = user_id);
CREATE POLICY ai_messages_delete_own ON public.ai_messages
    FOR DELETE TO authenticated USING ((select auth.uid()) = user_id);

CREATE INDEX IF NOT EXISTS idx_ai_conversations_user_updated
    ON public.ai_conversations(user_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_messages_conversation_user_created
    ON public.ai_messages(conversation_id, user_id, created_at);
